-- Inferred schema for the RTC attendance app.
-- Review against the live Supabase project before applying to production.

create table if not exists public.app_users (
  teacher_id text primary key,
  username text not null unique,
  pin text not null,
  name text not null default '',
  role text not null default 'teacher' check (role in ('admin', 'teacher')),
  room_ids text not null default '',
  active text not null default 'TRUE',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on column public.app_users.pin is
'Stores legacy plaintext PINs or pbkdf2_sha256$iterations$salt$hash values. New app writes use hashes.';

create table if not exists public.rooms (
  room_id text primary key,
  room_name text not null default '',
  level text not null default '',
  year text not null default '',
  room_no text not null default '',
  schedule_group text not null default ''
);

create table if not exists public.students (
  student_id text primary key,
  prefix text not null default '',
  first_name text not null default '',
  last_name text not null default '',
  level text not null default '',
  year text not null default '',
  room_no text not null default '',
  room_id text not null references public.rooms(room_id) on update cascade,
  active text not null default 'TRUE'
);

create table if not exists public.terms (
  term_id text primary key,
  term_name text not null default '',
  start_date date,
  end_date date,
  total_weeks integer not null default 0
);

create table if not exists public.school_days (
  date date not null,
  term_id text not null references public.terms(term_id) on update cascade,
  level_group text not null default '',
  schedule_group text not null default '',
  week_no text not null default '',
  month_key text not null default '',
  is_lineup_day text not null default 'TRUE',
  note text not null default '',
  primary key (date, term_id, schedule_group)
);

create table if not exists public.attendance (
  att_id text primary key,
  date date not null,
  term_id text not null references public.terms(term_id) on update cascade,
  week_no text not null default '',
  month_key text not null default '',
  room_id text not null references public.rooms(room_id) on update cascade,
  student_id text not null references public.students(student_id) on update cascade,
  status text not null check (status in ('P', 'A')),
  checked_by text not null default '',
  checked_at timestamptz not null default now()
);

create table if not exists public.room_lineup_exceptions (
  id text primary key,
  room_id text not null references public.rooms(room_id) on update cascade,
  term_id text not null references public.terms(term_id) on update cascade,
  exception_type text not null check (exception_type in ('DATE', 'WEEKDAY')),
  weekday integer check (weekday between 0 and 6),
  date date,
  is_lineup_day text not null default 'FALSE',
  note text not null default '',
  active text not null default 'TRUE',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint room_lineup_exceptions_target_check check (
    (exception_type = 'DATE' and date is not null and weekday is null) or
    (exception_type = 'WEEKDAY' and weekday is not null and date is null)
  )
);

create table if not exists public.audit_logs (
  log_id bigint generated by default as identity primary key,
  action text not null check (action in ('INSERT', 'UPDATE', 'DELETE')),
  att_id text,
  date date,
  term_id text,
  week_no text,
  month_key text,
  room_id text,
  student_id text,
  old_status text,
  new_status text,
  checked_by text,
  checked_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists idx_app_users_username on public.app_users(username);
create index if not exists idx_students_room_id on public.students(room_id);
create index if not exists idx_school_days_term_group_date on public.school_days(term_id, schedule_group, date);
create index if not exists idx_attendance_date_room on public.attendance(date, room_id);
create index if not exists idx_attendance_term_student on public.attendance(term_id, student_id);
create index if not exists idx_attendance_term_date on public.attendance(term_id, date);
create index if not exists idx_room_lineup_exceptions_room_term on public.room_lineup_exceptions(room_id, term_id);
create index if not exists idx_audit_logs_date_created_at on public.audit_logs(date, created_at desc);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists app_users_set_updated_at on public.app_users;
create trigger app_users_set_updated_at
before update on public.app_users
for each row execute function public.set_updated_at();

drop trigger if exists room_lineup_exceptions_set_updated_at on public.room_lineup_exceptions;
create trigger room_lineup_exceptions_set_updated_at
before update on public.room_lineup_exceptions
for each row execute function public.set_updated_at();

create or replace function public.log_attendance_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.audit_logs (
      action, att_id, date, term_id, week_no, month_key, room_id,
      student_id, old_status, new_status, checked_by, checked_at
    )
    values (
      'INSERT', new.att_id, new.date, new.term_id, new.week_no, new.month_key,
      new.room_id, new.student_id, null, new.status, new.checked_by, new.checked_at
    );
    return new;
  end if;

  if tg_op = 'UPDATE' then
    insert into public.audit_logs (
      action, att_id, date, term_id, week_no, month_key, room_id,
      student_id, old_status, new_status, checked_by, checked_at
    )
    values (
      'UPDATE', new.att_id, new.date, new.term_id, new.week_no, new.month_key,
      new.room_id, new.student_id, old.status, new.status, new.checked_by, new.checked_at
    );
    return new;
  end if;

  insert into public.audit_logs (
    action, att_id, date, term_id, week_no, month_key, room_id,
    student_id, old_status, new_status, checked_by, checked_at
  )
  values (
    'DELETE', old.att_id, old.date, old.term_id, old.week_no, old.month_key,
    old.room_id, old.student_id, old.status, null, old.checked_by, old.checked_at
  );

  return old;
end;
$$;

drop trigger if exists attendance_audit_log on public.attendance;
create trigger attendance_audit_log
after insert or update or delete on public.attendance
for each row execute function public.log_attendance_change();

create or replace view public.room_term_summary as
select
  a.term_id,
  a.room_id,
  coalesce(r.room_name, a.room_id) as room_name,
  coalesce(r.level, '') as level,
  coalesce(r.year, '') as year,
  coalesce(r.room_no, '') as room_no,
  coalesce(r.schedule_group, '') as schedule_group,
  count(*) filter (where a.status = 'P')::integer as present_count,
  count(*) filter (where a.status = 'A')::integer as absent_count,
  count(*)::integer as total_records,
  case
    when count(*) > 0 then round((count(*) filter (where a.status = 'P'))::numeric * 100 / count(*), 2)
    else 0
  end as present_percent,
  case
    when count(*) > 0 then round((count(*) filter (where a.status = 'A'))::numeric * 100 / count(*), 2)
    else 0
  end as absent_percent
from public.attendance a
left join public.rooms r on r.room_id = a.room_id
group by
  a.term_id,
  a.room_id,
  r.room_name,
  r.level,
  r.year,
  r.room_no,
  r.schedule_group;

create or replace view public.student_term_summary as
with student_attendance as (
  select
    a.term_id,
    a.room_id,
    a.student_id,
    count(*) filter (where a.status = 'P')::integer as present_count,
    count(*) filter (where a.status = 'A')::integer as absent_count,
    count(*)::integer as total_records
  from public.attendance a
  group by a.term_id, a.room_id, a.student_id
)
select
  sa.term_id,
  sa.room_id,
  coalesce(r.room_name, sa.room_id) as room_name,
  coalesce(r.level, s.level, '') as level,
  coalesce(r.year, s.year, '') as year,
  coalesce(r.room_no, s.room_no, '') as room_no,
  coalesce(r.schedule_group, '') as schedule_group,
  sa.student_id,
  coalesce(s.prefix, '') as prefix,
  coalesce(s.first_name, '') as first_name,
  coalesce(s.last_name, '') as last_name,
  sa.present_count,
  sa.absent_count,
  sa.total_records,
  case
    when sa.total_records > 0 then round(sa.present_count::numeric * 100 / sa.total_records, 2)
    else 0
  end as present_percent,
  case
    when sa.total_records > 0 then round(sa.absent_count::numeric * 100 / sa.total_records, 2)
    else 0
  end as absent_percent,
  case
    when sa.total_records > 0 and (sa.absent_count::numeric * 100 / sa.total_records) >= 20 then 'ตกกิจกรรม'
    when sa.total_records > 0 and (sa.absent_count::numeric * 100 / sa.total_records) >= 15 then 'เสี่ยงสูงมาก'
    when sa.total_records > 0 and (sa.absent_count::numeric * 100 / sa.total_records) >= 10 then 'เสี่ยงสูง'
    when sa.total_records > 0 and (sa.absent_count::numeric * 100 / sa.total_records) >= 5 then 'เฝ้าระวัง'
    else ''
  end as risk_level
from student_attendance sa
left join public.students s on s.student_id = sa.student_id
left join public.rooms r on r.room_id = sa.room_id;
